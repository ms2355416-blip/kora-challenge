  const getLanguage = () => {
    try {
      return localStorage.getItem("koraChallengeLanguage") ||
             localStorage.getItem("koraLanguage") ||
             "ar";
    } catch (_) {
      return "ar";
    }
  };

  function translateExtra(root = document) {
    const lang = getLanguage();
    if (lang === "ar" || !extraTranslations[lang]) return;

    const dictionary = extraTranslations[lang];
    const walker = document.createTreeWalker(
      root,
      NodeFilter.SHOW_TEXT
    );

    const nodes = [];
    while (walker.nextNode()) nodes.push(walker.currentNode);

    nodes.forEach(node => {
      const original = node.nodeValue;
      const trimmed = original.trim();
      if (!trimmed || !dictionary[trimmed]) return;

      const leading = original.match(/^\s*/)[0];
      const trailing = original.match(/\s*$/)[0];
      node.nodeValue = leading + dictionary[trimmed] + trailing;
    });

    root.querySelectorAll?.(
      "input[placeholder], input[aria-label], img[alt]"
    ).forEach(element => {
      ["placeholder", "aria-label", "alt"].forEach(attribute => {
        const value = element.getAttribute(attribute);
        if (value && dictionary[value]) {
          element.setAttribute(attribute, dictionary[value]);
        }
      });
    });
  }

  window.koraTranslateExtra = translateExtra;

  document.addEventListener("DOMContentLoaded", () => {
    translateExtra();

    const observer = new MutationObserver(() => {
      translateExtra();
    });

    observer.observe(document.body, {
      childList: true,
      subtree: true
    });

    window.addEventListener("storage", event => {
      if (
        event.key === "koraChallengeLanguage" ||
        event.key === "koraLanguage"
      ) {
        location.reload();
      }
    });
  });
